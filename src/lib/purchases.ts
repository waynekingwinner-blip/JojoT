let configured = false
let cachedPackages: PurchasesPackage[] = []

/** Safe to call more than once; only the first call configures. */
export async function initPurchases(): Promise<void> {
  if (purchaseMode() !== 'store' || configured) return
  try {
    await Purchases.setLogLevel({ level: import.meta.env.DEV ? LOG_LEVEL.DEBUG : LOG_LEVEL.ERROR })
    await Purchases.configure({ apiKey: API_KEY })
    configured = true
  } catch {
    // leave `configured` false — the app will show the paywall as
    // unavailable rather than pretending anything succeeded
  }
}

/** Derive the "$4.16 / month"-style line from the real price. */
function equivalentLine(amount: number, currency: string, id: PlanId): string {
  const fmt = (n: number) => {
    try {
      return new Intl.NumberFormat(undefined, { style: 'currency', currency }).format(n)
    } catch {
      return n.toFixed(2)
    }
  }
  if (id === 'weekly') return `${fmt(amount / 7)} / day`
  if (id === 'monthly') return `${fmt(amount / 4.345)} / week`
  return `${fmt(amount / 12)} / month`
}

/**
 * The tiers to show on the paywall, with the store's own localized
 * prices when they are available. Falls back to the static US copy
 * in 'mock', and returns [] in 'unavailable' so the paywall can say
 * so instead of inventing numbers.
 */
export async function loadPlans(): Promise<Plan[]> {
  const mode = purchaseMode()
  if (mode === 'mock') return PLANS
  if (mode === 'unavailable') return []

  await initPurchases()
  if (!configured) return []

  try {
    const { current } = await Purchases.getOfferings()
    if (!current?.availablePackages?.length) return []
    cachedPackages = current.availablePackages

    const priced = PLANS.map((base) => {
      const pkg = cachedPackages.find((p) => p.identifier === PACKAGE_FOR[base.id])
      if (!pkg) return null
      const { priceString, price, currencyCode, identifier } = pkg.product
      return {
        ...base,
        productId: identifier,
        price: priceString,
        per: `${priceString} per ${base.id === 'yearly' ? 'year' : base.id.replace('ly', '')}`,
        equivalent: equivalentLine(price, currencyCode, base.id),
      }
    }).filter((p): p is Plan => p !== null)

    return priced
  } catch {
    return []
  }
}

function entitlementFrom(info: CustomerInfo): Entitlement | null {
  const active = info.entitlements.active[ENTITLEMENT_ID]
  if (!active) return null

  const productId = active.productIdentifier
  const matched = PLANS.find((p) => productId.includes(p.id)) ?? getPlan(DEFAULT_PLAN)

  return {
    planId: matched.id,
    productId,
    purchasedISO: (active.latestPurchaseDate ?? '').slice(0, 10),
    renewsISO: (active.expirationDate ?? '').slice(0, 10),
  }
}

/**
 * The result of asking the store who this user is.
 *
 * 'unknown' is not the same as no entitlement, and conflating the two
 * is how you lock paying customers out: a flat `null` on a network
 * blip would overwrite the cached entitlement and drop a subscriber
 * onto the paywall. Callers must leave their cache alone on 'unknown'.
 */
export type EntitlementCheck =
  | { status: 'ok'; entitlement: Entitlement | null }
  | { status: 'unknown' }

/**
 * Ask the store who this user is. When it answers, it is the
 * authority — a lapsed or refunded subscription closes the gate, and
 * a reinstall opens it without the user hunting for Restore.
 */
export async function checkEntitlement(): Promise<EntitlementCheck> {
  const mode = purchaseMode()
  if (mode === 'mock') return { status: 'ok', entitlement: readReceipt() }
  // no key: nothing can be verified, so don't touch what is cached
  if (mode === 'unavailable') return { status: 'unknown' }

  await initPurchases()
  if (!configured) return { status: 'unknown' }

  try {
    const { customerInfo } = await Purchases.getCustomerInfo()
    return { status: 'ok', entitlement: entitlementFrom(customerInfo) }
  } catch {
    return { status: 'unknown' }
  }
}

export async function buy(planId: PlanId): Promise<PurchaseResult> {
  const mode = purchaseMode()

  if (mode === 'mock') {
    const plan = getPlan(planId)
    await new Promise((r) => setTimeout(r, LATENCY))
    const entitlement = mockEntitlement(plan)
    try {
      localStorage.setItem(RECEIPT_KEY, JSON.stringify(entitlement))
    } catch {
      /* ignore */
    }
    return { ok: true, entitlement }
  }

  if (mode === 'unavailable') return { ok: false, reason: 'failed' }

  await initPurchases()
  if (!configured) return { ok: false, reason: 'failed' }

  if (!cachedPackages.length) await loadPlans()
  const pkg = cachedPackages.find((p) => p.identifier === PACKAGE_FOR[planId])
  if (!pkg) return { ok: false, reason: 'failed' }

  try {
    const { customerInfo } = await Purchases.purchasePackage({ aPackage: pkg })
    const entitlement = entitlementFrom(customerInfo)
    if (!entitlement) return { ok: false, reason: 'failed' }
    return { ok: true, entitlement }
  } catch (e) {
    // RevenueCat surfaces a cancellation as a thrown error with a flag
    const cancelled = (e as { userCancelled?: boolean; code?: string })?.userCancelled
    return { ok: false, reason: cancelled ? 'cancelled' : 'failed' }
  }
}

export async function restore(): Promise<PurchaseResult> {
  const mode = purchaseMode()

  if (mode === 'mock') {
    await new Promise((r) => setTimeout(r, LATENCY))
    const found = readReceipt()
    return found ? { ok: true, entitlement: found } : { ok: false, reason: 'none-to-restore' }
  }

  if (mode === 'unavailable') return { ok: false, reason: 'failed' }

  await initPurchases()
  if (!configured) return { ok: false, reason: 'failed' }

  try {
    const { customerInfo } = await Purchases.restorePurchases()
    const entitlement = entitlementFrom(customerInfo)
    return entitlement
      ? { ok: true, entitlement }
      : { ok: false, reason: 'none-to-restore' }
  } catch {
    return { ok: false, reason: 'failed' }
  }
}

