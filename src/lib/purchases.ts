/* ============================================================
   purchases.ts — subscriptions, via RevenueCat + StoreKit 2.

   Three modes, decided at runtime by `purchaseMode()`:

     'store'        native build with an API key — the real thing
     'mock'         web / dev — fake receipts so preview and e2e work
     'unavailable'  native build with NO api key — the gate stays
                    shut and no prices are shown. Deliberately not a
                    free pass: shipping a build that hands the app
                    out for nothing, or that shows invented prices,
                    is worse than one that says it is unavailable.

   ⚠️ Under StoreKit 2 (purchases-ios 5.x, which this wraps),
   transactions are silently never recorded unless the In-App
   Purchase Key in the RevenueCat dashboard was generated by THIS
   app's Apple account. The symptom is $0 in RevenueCat while Apple
   really is charging people, and paying users locked out. See
   notes/REVENUECAT-SETUP.md step 3.
   ============================================================ */

import { Capacitor } from '@capacitor/core'
import {
  Purchases,
  LOG_LEVEL,
  type PurchasesPackage,
  type CustomerInfo,
} from '@revenuecat/purchases-capacitor'

/** Must match the entitlement identifier in the RevenueCat dashboard
    exactly. A mismatch here unlocks nothing for anyone who pays. */
export const ENTITLEMENT_ID = 'premium'

const API_KEY = (import.meta.env.VITE_REVENUECAT_IOS_KEY as string | undefined)?.trim() || ''

export type PlanId = 'weekly' | 'monthly' | 'yearly'

export type Plan = {
  id: PlanId
  productId: string
  title: string
  /** localized, e.g. "$7.99" or "￥1,200" — from the store when live */
  price: string
  per: string
  equivalent: string
  badge?: string
  periodDays: number
}

/** RevenueCat's standard package identifiers, in the offering. */
const PACKAGE_FOR: Record<PlanId, string> = {
  weekly: '$rc_weekly',
  monthly: '$rc_monthly',
  yearly: '$rc_annual',
}

/* Shape and copy for the three tiers. Prices here are the US
   defaults and act as the fallback; the live paywall overwrites
   them with the store's localized strings. */
export const PLANS: Plan[] = [
  {
    id: 'weekly',
    productId: 'jojot.premium.weekly',
    title: 'Weekly',
    price: '$7.99',
    per: '$7.99 per week',
    equivalent: '$1.14 / day',
    periodDays: 7,
  },
  {
    id: 'monthly',
    productId: 'jojot.premium.monthly',
    title: 'Monthly',
    price: '$14.99',
    per: '$14.99 per month',
    equivalent: '$3.75 / week',
    badge: 'Most popular',
    periodDays: 30,
  },
  {
    id: 'yearly',
    productId: 'jojot.premium.yearly',
    title: 'Yearly',
    price: '$49.99',
    per: '$49.99 per year',
    equivalent: '$4.16 / month',
    badge: 'Save 72%',
    periodDays: 365,
  },
]

export const DEFAULT_PLAN: PlanId = 'monthly'

export function getPlan(id: PlanId): Plan {
  return PLANS.find((p) => p.id === id) ?? PLANS[1]
}

export type Entitlement = {
  planId: PlanId
  productId: string
  purchasedISO: string
  renewsISO: string
}

export type PurchaseResult =
  | { ok: true; entitlement: Entitlement }
  | { ok: false; reason: 'cancelled' | 'failed' | 'none-to-restore' }

export type PurchaseMode = 'store' | 'mock' | 'unavailable'

export function purchaseMode(): PurchaseMode {
  if (!Capacitor.isNativePlatform()) return 'mock'
  return API_KEY ? 'store' : 'unavailable'
}

